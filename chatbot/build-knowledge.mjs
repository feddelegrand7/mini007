// Builds src/knowledge.js, the documentation the chatbot answers from.
//
// It reads the site's source pages in navbar order (plus NEWS.md), drops the
// YAML front matter and chunk options, and labels each page with its URL so
// the bot can link to it. Run it again whenever the docs change:
//
//   node chatbot/build-knowledge.mjs
//
// then redeploy the Worker (see chatbot/README.md).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const siteUrl = "https://mini007.com/";

const pages = [
  ["index.qmd", "Home"],
  ["agents.qmd", "Agents"],
  ["leadagent.qmd", "LeadAgent"],
  ["react.qmd", "ReActAgent"],
  ["router.qmd", "RouterAgent"],
  ["tools.qmd", "Tools"],
  ["workflow.qmd", "Workflow"],
  ["streaming.qmd", "Streaming"],
  ["learning.qmd", "Learning"],
  ["testing.qmd", "Testing"],
  ["NEWS.md", "News (changelog)"],
];

function clean(source) {
  return source
    .replace(/^---\n[\s\S]*?\n---\n/, "")       // YAML front matter
    .replace(/^#\|.*\n/gm, "")                 // chunk options
    .replace(/```\{r[^}]*\}/g, "```r")          // ```{r, eval=FALSE} -> ```r
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const sections = pages.map(([file, title]) => {
  const url = siteUrl + file.replace(/\.(qmd|md)$/, ".html");
  const text = clean(readFileSync(join(root, file), "utf8"));
  return `<page title="${title}" url="${url}">\n${text}\n</page>`;
});

const knowledge = sections.join("\n\n");
const out =
  "// Generated by build-knowledge.mjs - do not edit by hand.\n" +
  `export const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`;

writeFileSync(join(root, "chatbot", "src", "knowledge.js"), out);
console.log(`Wrote chatbot/src/knowledge.js: ${pages.length} pages, ${knowledge.length} characters.`);
